import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const withoutExports=s=>s.replace(/^import .*?;\n/gm,'').replace(/\bexport (?=(?:const|function|async function))/g,'');
const chrome=withoutExports(fs.readFileSync(path.join(root,'commerce/chrome.mjs'),'utf8'));
const catalog=withoutExports(fs.readFileSync(path.join(root,'commerce/catalog.mjs'),'utf8'));
const research=withoutExports(fs.readFileSync(path.join(root,'commerce/research.mjs'),'utf8'));
const routes=JSON.parse(fs.readFileSync(path.join(root,'commerce/routes.json'),'utf8'));
const metadata=`const ROUTES=new Set(${JSON.stringify(routes.routes)});\nconst STATIC_FILES=new Set(${JSON.stringify(routes.assets)});\nconst PRODUCT_DESTINATIONS=${JSON.stringify(routes.legacyProducts)};\n`;
const worker=fs.readFileSync(path.join(root,'commerce/worker.mjs'),'utf8');
fs.writeFileSync(path.join(root,'_worker.js'), '// Generated by maintenance/build-worker.mjs. Edit commerce sources.\n'+chrome+'\n'+research+'\n'+catalog+'\n'+metadata+worker);
console.log('Built Pikobuy worker:',routes.routes.length,'editorial routes.');
