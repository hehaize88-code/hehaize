function pdMedia(html,p){
 const section=html.split(/<section\b[^>]*class="product-list"/i)[0].split(/<(?:section|div)\b[^>]*class="product-detail"[^>]*>/i).pop();
 const gallery=new Set(p.imgs),qc=new Set(),details=new Set(),styles=[],stack=[];
 for(const token of section.matchAll(/<(\/?)([\w-]+)\b[^>]*>/g)){
  const [tag,closing,kind]=token;
  if(closing){
   const i=stack.findLastIndex(el=>el.kind===kind);
   if(i>=0)stack.length=i;
   continue;
  }
  const a=pdAttributes(tag), markers=[a.class,a.id,a['data-role'],a['data-type'],a['data-image-type'],a.alt].filter(Boolean).join(' ');
  const parent=stack.at(-1);
  let type=parent?.type;
  let optionLink=parent?.optionLink || '';
  const sourceLink=a['data-weidian-url'] || a['data-style-url'] || a.href;
  if(sourceLink){
   try{
    const u=new URL(sourceLink);
    if(u.protocol==='https:' && /^(?:www\.)?weidian\.com$/.test(u.hostname) && u.pathname==='/item.html' && /^\d+$/.test(u.searchParams.get('itemID'))){
     const id=u.searchParams.get('itemID');
     if(id!==p.id || u.hash || [...u.searchParams.keys()].some(k=>/^sku(?:_?id)?$/i.test(k)))optionLink=u.href;
    }
   }catch{}
  }
  const skuId=a['data-sku-id'] || parent?.skuId || '';
  const optionLabel=a['data-option-name'] || a['data-style-name'] || parent?.optionLabel || '';
  if(/\b(?:qc(?:[-_ ](?:photos?|images?|gallery))?|quality[-_ ]control)\b|质检图/i.test(markers))type='qc';
  else if(/\b(?:styles|variants|sku[-_](?:items?|list|gallery)|style[-_](?:items?|gallery))\b/i.test(markers))type='style';
  else if(/\b(?:product-description|product-content|detail-images|product-details-content)\b/.test(markers))type='detail';
  if(kind==='img'&&type){
   const raw=a['data-src']||a['data-original']||a.src;
   const src=raw&&media(raw);
   if(src && type==='style'){
    const name=optionLabel || a.alt || '';
    const link=optionLink || (/^\d+$/.test(skuId) && p.original ? p.original+'#sku_'+p.id+'_'+encodeURIComponent(name).replace(/_/g,'%5F')+'_'+skuId : '');
    if(!styles.some(v=>v.image===src && v.link===link))styles.push({image:src,name,link});
   }else if(src)(type==='qc'?qc:details).add(src);
  }
  if(!/^(?:img|br|input|meta|link|hr|source|wbr|area|base|embed|param|track)$/.test(kind)&&!tag.endsWith('/>'))stack.push({kind,type,skuId,optionLabel,optionLink});
 }
 for(const src of gallery)details.add(src);
 for(const src of qc){gallery.delete(src);details.delete(src)}
 return {gallery:[...gallery],details:[...details],qc:[...qc],styles};
}
