import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { products } from "../data/site.js";

const destination = resolve("data/main-catalog.js");
const concurrency = 8;
const retries = 3;

function decodeHtml(value) {
  return value
    .replaceAll("&amp;", "&")
    .replaceAll("&quot;", '"')
    .replaceAll("&#039;", "'")
    .replaceAll("&#39;", "'");
}

async function fetchText(url) {
  let lastError;
  for (let attempt = 1; attempt <= retries; attempt += 1) {
    try {
      const response = await fetch(url, {
        headers: { "user-agent": "Hubbuy-Sheet-Catalog-Sync/1.0" },
        signal: AbortSignal.timeout(30_000),
      });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return await response.text();
    } catch (error) {
      lastError = error;
      if (attempt < retries) await new Promise((resolveDelay) => setTimeout(resolveDelay, attempt * 750));
    }
  }
  throw lastError;
}

async function resolveProduct(product) {
  const url = `https://www.cnbuycha.com/AllProducts/?q=${encodeURIComponent(product.sourceId)}`;
  const html = await fetchText(url);
  const count = Number(html.match(/<div class="results-summary">(\d+) products?<\/div>/)?.[1] || 0);
  const card = html.match(/<article class="product-card[\s\S]*?<\/article>/)?.[0] || "";
  const path = card.match(/<a href="([^"]+)" class="product-image">/)?.[1];
  const image = card.match(/<img src="([^"]+)"/)?.[1];
  const sourceIdPresent = html.includes(`value="${product.sourceId}"`);

  if (count !== 1 || !path || !image || !sourceIdPresent) {
    throw new Error(`Unable to resolve source ${product.sourceId}: count=${count}, path=${path || "missing"}, image=${image || "missing"}`);
  }

  return {
    sourceId: product.sourceId,
    path: decodeHtml(path),
    image: decodeHtml(image),
  };
}

async function mapConcurrent(items, worker) {
  const results = new Array(items.length);
  let nextIndex = 0;

  async function run() {
    while (nextIndex < items.length) {
      const index = nextIndex;
      nextIndex += 1;
      results[index] = await worker(items[index]);
      process.stdout.write(`Resolved ${index + 1}/${items.length}: ${items[index].sourceId}\n`);
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, run));
  return results;
}

const records = await mapConcurrent(products, resolveProduct);
const duplicatePaths = records.filter((record, index) => records.findIndex((item) => item.path === record.path) !== index);
if (duplicatePaths.length) {
  throw new Error(`Duplicate live product paths: ${duplicatePaths.map((record) => record.path).join(", ")}`);
}

const source = [
  "// Generated by scripts/sync-main-catalog.mjs. Do not edit by hand.",
  `// Synced from the live catalog on ${new Date().toISOString().slice(0, 10)}.`,
  "export const mainCatalogBySourceId = new Map([",
  ...records.map((record) => `  [${JSON.stringify(record.sourceId)}, ${JSON.stringify({ path: record.path, image: record.image })}],`),
  "]);",
  "",
].join("\n");

writeFileSync(destination, source);

const currentSiteSource = readFileSync(resolve("data/site.js"), "utf8");
for (const product of products) {
  if (!currentSiteSource.includes(JSON.stringify(product.sourceId))) {
    throw new Error(`Source ID disappeared while syncing: ${product.sourceId}`);
  }
}

console.log(`Wrote ${records.length} live product mappings to ${destination}`);
